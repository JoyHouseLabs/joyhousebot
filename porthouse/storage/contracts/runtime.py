    def reset_runtime_run(self, run_id: str) -> bool: ...

    def suspend_run_for_approval(self, **kwargs: Any) -> bool: ...

    def suspend_run_for_reconciliation(self, **kwargs: Any) -> bool: ...

    def list_runtime_runs(self, **kwargs: Any) -> list[Any]: ...


