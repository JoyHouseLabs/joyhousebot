@dataclass(frozen=True, slots=True)
class RuntimeStores:
    """Explicit capability views over one transactional storage backend."""

    runs: RunStorePort
    tasks: TaskStorePort
    events: EventStorePort
    graphs: GraphStorePort
    workers: WorkerStorePort
    catalog: AgentCatalogStorePort
    logs: RuntimeLogStorePort
    traces: TraceStorePort
    scenarios: ScenarioStorePort
    maintenance: MaintenanceStorePort
    execution: ExecutionStorePort
    observability: ObservabilityStorePort
    reconciliations: ReconciliationStorePort
    experiments: ExperimentStorePort
    team_workspace: TeamWorkspaceStorePort
    planning: PlanningStorePort
    plan_confirmations: PlanConfirmationStorePort
    clarifications: ClarificationStorePort
    invocations: InvocationStorePort
    workflows: WorkflowStorePort
    graph_patches: GraphPatchStorePort
    app_dependencies: AppDependencyStorePort

    @classmethod
    def from_backend(cls, backend: object) -> RuntimeStores:
        """Expose narrow views without splitting the backend transaction boundary."""
        explicit_views = getattr(type(backend), "runtime_stores", None)
        if callable(explicit_views):
            return cast(RuntimeStores, explicit_views(backend))
        return cls(
            runs=cast(RunStorePort, backend),
            tasks=cast(TaskStorePort, backend),
            events=cast(EventStorePort, backend),
            graphs=cast(GraphStorePort, backend),
            workers=cast(WorkerStorePort, backend),
            catalog=cast(AgentCatalogStorePort, backend),
            logs=cast(RuntimeLogStorePort, backend),
            traces=cast(TraceStorePort, backend),
            scenarios=cast(ScenarioStorePort, backend),
            maintenance=cast(MaintenanceStorePort, backend),
            execution=cast(ExecutionStorePort, backend),
            observability=cast(ObservabilityStorePort, backend),
            reconciliations=cast(ReconciliationStorePort, backend),
            experiments=cast(ExperimentStorePort, backend),
            team_workspace=cast(TeamWorkspaceStorePort, backend),
            planning=cast(PlanningStorePort, backend),
            plan_confirmations=cast(PlanConfirmationStorePort, backend),
            clarifications=cast(ClarificationStorePort, backend),
            invocations=cast(InvocationStorePort, backend),
            workflows=cast(WorkflowStorePort, backend),
            graph_patches=cast(GraphPatchStorePort, backend),
            app_dependencies=cast(AppDependencyStorePort, backend),
        )
